"""Standalone HTML research report for an Indian-stock analysis run.

Reuses the upstream TradingAgents renderer (one self-contained page: rating, the
analyst reports, the bull/bear debate, the risk debate and the portfolio decision) and
adds an audit section with live links so every claim can be checked at the source.
"""

from __future__ import annotations

from html import escape
from urllib.parse import quote

from tradingagents.dataflows.vendors.india.instruments import INDEX_KEYS, InstrumentMaster
from tradingagents.report_html import render_report
from tradingagents.reporting import _report_parts

_CSS = """
<style>
.audit{margin:2.5rem 0 1rem;padding:1.25rem 1.5rem;border:1px solid #8884;border-radius:10px}
.audit h2{margin-top:0}.audit ul{padding-left:1.1rem}.audit li{margin:.35rem 0}
.audit .note{font-size:.85rem;opacity:.75;margin-top:.8rem}
</style>
"""


def audit_links(ticker: str) -> list[tuple[str, str, str]]:
    """``(label, url, what to verify)`` for an NSE/BSE ticker or index."""
    base, exchange = InstrumentMaster.split_symbol(ticker)
    compact = base.replace(" ", "")
    if compact in INDEX_KEYS:
        name = INDEX_KEYS[compact][1]
        return [
            ("NSE India: indices", "https://www.nseindia.com/market-data/live-market-indices",
             f"Live {name} level and constituents"),
            ("TradingView chart", f"https://www.tradingview.com/symbols/{quote(name.replace(' ', ''))}/",
             "Cross-check price action"),
        ]
    sym = quote(base, safe="")
    links = [
        ("Screener.in: company page", f"https://www.screener.in/company/{sym}/consolidated/",
         "P/E, ROCE, ROE, quarterly results, shareholding (the fundamentals source)"),
        ("NSE India: quote", f"https://www.nseindia.com/get-quotes/equity?symbol={sym}",
         "Official quote, delivery %, announcements and corporate actions"),
        ("Moneycontrol (search)",
         f"https://www.google.com/search?q={quote('site:moneycontrol.com ' + base + ' share price')}",
         "Moneycontrol coverage, financials and news for the company"),
        ("TradingView chart", f"https://www.tradingview.com/symbols/{'NSE' if exchange == 'NSE' else 'BSE'}-{sym}/",
         "Cross-check price action and indicators"),
    ]
    return links


def render_html(ticker: str, final_state: dict, settings: dict | None = None) -> str:
    """The downloadable report: upstream page plus the audit section."""
    page = render_report(ticker, final_state, settings, _report_parts(final_state))
    items = "".join(
        f'<li><a href="{escape(url, quote=True)}" rel="noopener noreferrer" target="_blank">{escape(label)}</a>'
        f" &mdash; {escape(why)}</li>"
        for label, url, why in audit_links(ticker)
    )
    section = (
        '<section class="audit" id="audit"><h2>Audit links</h2>'
        "<p>Open these to verify the figures quoted in this report against the source.</p>"
        f"<ul>{items}</ul>"
        '<p class="note">Prices come from Upstox, fundamentals from Screener.in and news from the Indian '
        "business press. Generated by AI agents for research and paper trading; this is not investment "
        "advice.</p></section>"
    )
    if "</main>" in page:
        page = page.replace("</main>", section + "\n</main>", 1)
    else:
        page = page.replace("</body>", section + "</body>", 1)
    return page.replace("</head>", _CSS + "</head>", 1)
